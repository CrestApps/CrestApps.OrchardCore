namespace CrestApps.OrchardCore.Products.Core.Listing;

/// <summary>
/// The names of the filter styles the Product Listing feature registers.
/// </summary>
public static class ProductFacetStyles
{
    /// <summary>
    /// A list of options with their counts. It is the default, so it adds no alternate.
    /// </summary>
    public const string List = "List";

    /// <summary>
    /// A row of buttons, which suits short values such as sizes.
    /// </summary>
    public const string Buttons = "Buttons";

    /// <summary>
    /// A row of color swatches.
    /// </summary>
    public const string Swatches = "Swatches";
}
